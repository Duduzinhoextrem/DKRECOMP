"""check_content.py: what may not be published (docs/LEGAL.md), checked on synthetic names and bytes."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "tools"))

import check_content  # noqa: E402


def test_game_files_and_derived_outputs_are_rejected():
    for path in ("game.nsp", "user_files/exefs/main", "generated/dkctf_v0/main/f_0000.c", "reports/x.json",
                 "SwitchExtract/prod.keys", "prod.keys", "my-title.keys", "romfs.bin", "a/pipelines.bin",
                 "shaders/x.dkrspv", "capture.bmp", "dkctf.exe", "main.img", "config.local.toml",
                 "DKRecomp-Portatil/LEIA-ME.txt", "toolchain/sdl3/SDL3.dll"):
        assert check_content.problem(path, b"x") is not None, path


def test_project_files_pass():
    for path, data in (("runtime/src/hid.c", b"int x;\n"), ("README.md", b"# DKRecomp\n"),
                       ("tools/dkrecomp/recomp/lifter.py", b"'GENERATED BY DKRecomp'\n")):
        assert check_content.problem(path, data) is None, path


def test_content_rules():
    assert "binário" in check_content.problem("tests/data.dat", b"abc\0def")
    assert "gerado" in check_content.problem("src/x.c", b"/* GENERATED BY DKRecomp - do not edit. */")
    assert "pessoal" in check_content.problem("docs/notes.md", b"Run from C:\\Users\\someone\\DKRECOMP")
    assert "grande" in check_content.problem("docs/big.txt", b"a" * (check_content.MAX_BYTES + 1))
