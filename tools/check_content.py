"""Fail before a push if Git would publish a game file, something derived from one, or a personal path.

Usage (from the project root):
    .venv/Scripts/python tools/check_content.py

Checks every tracked file and every untracked file that `git add -A` would pick up (ignored files are skipped).
The rules follow docs/LEGAL.md. Exit code 0 means nothing was found.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from typing import List, Optional

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Game containers and files, and what DKRecomp derives from them.
FORBIDDEN_EXTENSIONS = {
    ".nsp", ".xci", ".nca", ".nsz", ".xcz", ".tik", ".cert", ".nso", ".npdm", ".nacp", ".keys",
    ".img", ".maxwell", ".spv", ".dkrspv", ".bmp", ".arc", ".pak", ".mp4",
    ".exe", ".dll", ".pdb", ".o", ".obj", ".lib",
}
FORBIDDEN_NAMES = {"prod.keys", "title.keys", "keys.txt", "romfs.bin", "pipelines.bin", "config.local.toml"}
FORBIDDEN_FOLDERS = ("game original meu/", "user_files/", "SwitchExtract/", "build/", "generated/", "reports/",
                     "refs/", "toolchain/", "DKRecomp-Portatil/", ".venv/")
# Text files written by the project may mention these markers; they are the only exceptions.
GENERATED_MARKER = "GENERATED BY DKRecomp"
CHECKER_FILES = {"tools/check_content.py", "tests/python/test_check_content.py"}
MARKER_ALLOWED = {"docs/LEGAL.md", "docs/LEGAL.en.md", "tools/dkrecomp/recomp/lifter.py"} | CHECKER_FILES
PERSONAL_PATH = re.compile(r"[A-Za-z]:[\\/]+Users[\\/]+[^\\/\s`'\"]+", re.IGNORECASE)
MAX_BYTES = 2 << 20


def problem(path: str, data: Optional[bytes]) -> Optional[str]:
    """The reason `path` (relative, forward slashes) must not be published, or None. `data` is its content."""
    lower = path.lower()
    name = lower.rsplit("/", 1)[-1]
    for folder in FORBIDDEN_FOLDERS:
        if lower.startswith(folder.lower()):
            return f"pasta proibida ({folder})"
    if name in FORBIDDEN_NAMES or name.endswith("keys.txt"):
        return "arquivo proibido (chaves, dados do jogo ou configuração pessoal)"
    extension = os.path.splitext(name)[1]
    if extension in FORBIDDEN_EXTENSIONS:
        return f"extensão proibida ({extension})"
    if data is None:
        return None
    if len(data) > MAX_BYTES:
        return f"arquivo grande demais ({len(data) >> 20} MiB)"
    if b"\0" in data[:8192]:
        return "arquivo binário"
    text = data.decode("utf-8", "replace")
    if GENERATED_MARKER in text and path not in MARKER_ALLOWED:
        return "código gerado a partir do jogo"
    if path not in CHECKER_FILES and PERSONAL_PATH.search(text):
        return "caminho pessoal (C:\\Users\\...)"
    return None


def candidates() -> List[str]:
    def listed(*args: str) -> List[str]:
        out = subprocess.run(["git", "ls-files", "-z", *args], cwd=ROOT, check=True, capture_output=True).stdout
        return [p for p in out.decode("utf-8").split("\0") if p]
    return sorted(set(listed("--cached") + listed("--others", "--exclude-standard")))


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    found = []
    for path in candidates():
        full = os.path.join(ROOT, path)
        data = None
        if os.path.isfile(full):
            with open(full, "rb") as stream:
                data = stream.read(MAX_BYTES + 1)
        reason = problem(path, data)
        if reason:
            found.append((path, reason))
    for path, reason in found:
        print(f"PROIBIDO  {path}: {reason}")
    if found:
        print(f"\n{len(found)} arquivo(s) não podem ir para o GitHub. Veja docs/LEGAL.md.")
        return 1
    print("ok: nenhum arquivo do jogo, derivado dele ou caminho pessoal no que o Git publicaria.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
